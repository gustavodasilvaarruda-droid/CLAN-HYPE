"""Testes reais do gatilho PostgreSQL de avanço de rodadas.

Executados apenas com HYPE_TEST_DATABASE_URL definido, usando um banco efêmero.
O site e o Supabase de produção nunca são acessados por estes testes.
"""
import os
import unittest
from pathlib import Path

try:
    import psycopg
except ImportError:
    psycopg = None


@unittest.skipUnless(os.environ.get("HYPE_TEST_DATABASE_URL") and psycopg,
                     "Exige PostgreSQL de teste e psycopg")
class AutoAdvanceSQLTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.dsn = os.environ["HYPE_TEST_DATABASE_URL"]
        with psycopg.connect(cls.dsn, autocommit=True) as conn:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS public.torneios (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    status_torneio TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS public.partidas_torneio (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    torneio_id BIGINT NOT NULL REFERENCES public.torneios(id),
                    rodada INTEGER NOT NULL,
                    ordem INTEGER NOT NULL,
                    jogador1_email TEXT,
                    jogador1_nick TEXT,
                    jogador2_email TEXT,
                    jogador2_nick TEXT,
                    vencedor_email TEXT,
                    vencedor_nick TEXT,
                    status TEXT NOT NULL DEFAULT 'pendente',
                    CONSTRAINT partida_torneio_posicao_unica
                        UNIQUE (torneio_id, rodada, ordem)
                );
            """)
            # As roles do Supabase não existem no PostgreSQL virgem do CI.
            conn.execute("""
                DO $setup$
                BEGIN
                  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
                    CREATE ROLE anon NOLOGIN;
                  END IF;
                  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
                    CREATE ROLE authenticated NOLOGIN;
                  END IF;
                END
                $setup$;
            """)
            migration = (Path(__file__).resolve().parents[1] / "supabase" /
                         "migrations" /
                         "20261104_hype_avanco_automatico_rodadas.sql").read_text()
            conn.execute(migration)

    def setUp(self):
        self.conn = psycopg.connect(self.dsn)
        self.addCleanup(self.conn.close)
        self.addCleanup(self.conn.rollback)

    def tournament(self, status="em_andamento"):
        return self.conn.execute(
            "INSERT INTO public.torneios(status_torneio) VALUES(%s) RETURNING id",
            (status,)).fetchone()[0]

    def match(self, tournament, order, a, b, winner=None, round_=1):
        status = "finalizada" if winner else "pendente"
        return self.conn.execute(
            """INSERT INTO public.partidas_torneio (
                torneio_id, rodada, ordem,
                jogador1_email, jogador1_nick, jogador2_email, jogador2_nick,
                vencedor_email, vencedor_nick, status
            ) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
            (tournament, round_, order, a, a, b, b, winner, winner, status)
        ).fetchone()[0]

    def finish(self, match_id, winner):
        self.conn.execute(
            """UPDATE public.partidas_torneio
                  SET vencedor_email=%s, vencedor_nick=%s, status='finalizada'
                WHERE id=%s""", (winner, winner, match_id))

    def round_matches(self, tournament, round_):
        return self.conn.execute(
            """SELECT jogador1_email, jogador2_email, status
                 FROM public.partidas_torneio
                WHERE torneio_id=%s AND rodada=%s ORDER BY ordem""",
            (tournament, round_)).fetchall()

    def test_advances_only_after_all_matches_finished(self):
        t = self.tournament()
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "a@test")
        self.assertEqual(self.round_matches(t, 2), [])
        self.finish(b, "d@test")
        self.assertEqual(self.round_matches(t, 2),
                         [("a@test", "d@test", "pendente")])
        # Repetir atualização não pode criar partidas duplicadas.
        self.finish(b, "d@test")
        self.assertEqual(len(self.round_matches(t, 2)), 1)

    def test_bye_advances_with_other_winner(self):
        t = self.tournament()
        self.match(t, 1, "bye@test", None, winner="bye@test")
        duel = self.match(t, 2, "a@test", "b@test")
        self.finish(duel, "b@test")
        self.assertEqual(self.round_matches(t, 2),
                         [("bye@test", "b@test", "pendente")])

    def test_inactive_tournament_stays_unchanged(self):
        t = self.tournament(status="cancelado")
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "a@test")
        self.finish(b, "c@test")
        self.assertEqual(self.round_matches(t, 2), [])

    def test_last_match_keeps_champion_for_admin_review(self):
        t = self.tournament()
        final = self.match(t, 1, "a@test", "b@test")
        self.finish(final, "a@test")
        self.assertEqual(self.round_matches(t, 2), [])

    def test_invalid_winner_blocks_automatic_advance(self):
        t = self.tournament()
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "intruso@test")
        self.finish(b, "c@test")
        self.assertEqual(self.round_matches(t, 2), [])

    def test_never_overwrites_an_existing_next_round(self):
        t = self.tournament()
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.match(t, 1, "manual1@test", "manual2@test", round_=2)
        self.finish(a, "a@test")
        self.finish(b, "c@test")
        self.assertEqual(self.round_matches(t, 2),
                         [("manual1@test", "manual2@test", "pendente")])


if __name__ == "__main__":
    unittest.main()
