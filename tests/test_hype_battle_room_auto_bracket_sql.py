"""Testes reais do gatilho PostgreSQL de avanço de rodadas.

Executados apenas com HYPE_TEST_DATABASE_URL definido, usando um banco efêmero.
O site e o Supabase de produção nunca são acessados por estes testes.
"""
import os
import unittest
from pathlib import Path

try:
    import psycopg
except ImportError:
    psycopg = None


@unittest.skipUnless(os.environ.get("HYPE_TEST_DATABASE_URL") and psycopg,
                     "Exige PostgreSQL de teste e psycopg")
class AutoAdvanceSQLTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.dsn = os.environ["HYPE_TEST_DATABASE_URL"]
        with psycopg.connect(cls.dsn, autocommit=True) as conn:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS public.usuarios_clan (
                    email TEXT PRIMARY KEY
                );
                CREATE TABLE IF NOT EXISTS public.temporadas (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                );
                CREATE TABLE IF NOT EXISTS public.torneios (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    status_torneio TEXT NOT NULL,
                    inscricoes_abertas BOOLEAN NOT NULL DEFAULT FALSE,
                    campeao_email TEXT,
                    campeao_nick TEXT,
                    vice_campeao_email TEXT,
                    vice_campeao_nick TEXT,
                    finalizado_em TIMESTAMPTZ,
                    ranking_ativo BOOLEAN NOT NULL DEFAULT FALSE,
                    ranking_processado BOOLEAN NOT NULL DEFAULT FALSE,
                    temporada_id BIGINT REFERENCES public.temporadas(id),
                    pontos_campeao INTEGER NOT NULL DEFAULT 10,
                    pontos_vice INTEGER NOT NULL DEFAULT 6
                );
                CREATE TABLE IF NOT EXISTS public.inscricoes_torneio (
                    torneio_id BIGINT NOT NULL REFERENCES public.torneios(id),
                    usuario_email TEXT NOT NULL REFERENCES public.usuarios_clan(email),
                    PRIMARY KEY (torneio_id, usuario_email)
                );
                CREATE TABLE IF NOT EXISTS public.ranking_temporada (
                    temporada_id BIGINT NOT NULL REFERENCES public.temporadas(id),
                    usuario_email TEXT NOT NULL REFERENCES public.usuarios_clan(email),
                    pontos INTEGER NOT NULL DEFAULT 0,
                    vitorias INTEGER NOT NULL DEFAULT 0,
                    podios INTEGER NOT NULL DEFAULT 0,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                    UNIQUE (temporada_id, usuario_email)
                );
                CREATE TABLE IF NOT EXISTS public.partidas_torneio (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    torneio_id BIGINT NOT NULL REFERENCES public.torneios(id),
                    rodada INTEGER NOT NULL,
                    ordem INTEGER NOT NULL,
                    jogador1_email TEXT,
                    jogador1_nick TEXT,
                    jogador2_email TEXT,
                    jogador2_nick TEXT,
                    vencedor_email TEXT,
                    vencedor_nick TEXT,
                    status TEXT NOT NULL DEFAULT 'pendente',
                    CONSTRAINT partida_torneio_posicao_unica
                        UNIQUE (torneio_id, rodada, ordem)
                );
            """)
            # As roles do Supabase não existem no PostgreSQL virgem do CI.
            conn.execute("""
                DO $setup$
                BEGIN
                  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
                    CREATE ROLE anon NOLOGIN;
                  END IF;
                  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
                    CREATE ROLE authenticated NOLOGIN;
                  END IF;
                END
                $setup$;
            """)
            migration = (Path(__file__).resolve().parents[1] / "supabase" /
                         "migrations" /
                         "20261104_hype_avanco_automatico_rodadas.sql").read_text()
            conn.execute(migration)
            champion_migration = (Path(__file__).resolve().parents[1] / "supabase" /
                                  "migrations" /
                                  "20261104_hype_encerramento_torneio_ranking_auto.sql").read_text()
            conn.execute(champion_migration)

    def setUp(self):
        self.conn = psycopg.connect(self.dsn)
        self.addCleanup(self.conn.close)
        self.addCleanup(self.conn.rollback)

    def tournament(self, status="em_andamento"):
        return self.conn.execute(
            "INSERT INTO public.torneios(status_torneio) VALUES(%s) RETURNING id",
            (status,)).fetchone()[0]

    def match(self, tournament, order, a, b, winner=None, round_=1):
        status = "finalizada" if winner else "pendente"
        return self.conn.execute(
            """INSERT INTO public.partidas_torneio (
                torneio_id, rodada, ordem,
                jogador1_email, jogador1_nick, jogador2_email, jogador2_nick,
                vencedor_email, vencedor_nick, status
            ) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
            (tournament, round_, order, a, a, b, b, winner, winner, status)
        ).fetchone()[0]

    def finish(self, match_id, winner):
        self.conn.execute(
            """UPDATE public.partidas_torneio
                  SET vencedor_email=%s, vencedor_nick=%s, status='finalizada'
                WHERE id=%s""", (winner, winner, match_id))

    def round_matches(self, tournament, round_):
        return self.conn.execute(
            """SELECT jogador1_email, jogador2_email, status
                 FROM public.partidas_torneio
                WHERE torneio_id=%s AND rodada=%s ORDER BY ordem""",
            (tournament, round_)).fetchall()

    def test_advances_only_after_all_matches_finished(self):
        t = self.tournament()
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "a@test")
        self.assertEqual(self.round_matches(t, 2), [])
        self.finish(b, "d@test")
        self.assertEqual(self.round_matches(t, 2),
                         [("a@test", "d@test", "pendente")])
        # Repetir atualização não pode criar partidas duplicadas.
        self.finish(b, "d@test")
        self.assertEqual(len(self.round_matches(t, 2)), 1)

    def test_bye_advances_with_other_winner(self):
        t = self.tournament()
        self.match(t, 1, "bye@test", None, winner="bye@test")
        duel = self.match(t, 2, "a@test", "b@test")
        self.finish(duel, "b@test")
        self.assertEqual(self.round_matches(t, 2),
                         [("bye@test", "b@test", "pendente")])

    def test_inactive_tournament_stays_unchanged(self):
        t = self.tournament(status="cancelado")
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "a@test")
        self.finish(b, "c@test")
        self.assertEqual(self.round_matches(t, 2), [])

    def test_last_match_keeps_champion_for_admin_review(self):
        t = self.tournament()
        final = self.match(t, 1, "a@test", "b@test")
        self.finish(final, "a@test")
        self.assertEqual(self.round_matches(t, 2), [])

    def test_invalid_winner_blocks_automatic_advance(self):
        t = self.tournament()
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "intruso@test")
        self.finish(b, "c@test")
        self.assertEqual(self.round_matches(t, 2), [])

    def test_never_overwrites_an_existing_next_round(self):
        t = self.tournament()
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.match(t, 1, "manual1@test", "manual2@test", round_=2)
        self.finish(a, "a@test")
        self.finish(b, "c@test")
        self.assertEqual(self.round_matches(t, 2),
                         [("manual1@test", "manual2@test", "pendente")])


    def enroll(self, tournament_id, *emails):
        for email in emails:
            self.conn.execute(
                "INSERT INTO public.usuarios_clan(email) VALUES (%s) ON CONFLICT DO NOTHING",
                (email,))
            self.conn.execute(
                """INSERT INTO public.inscricoes_torneio(torneio_id,usuario_email)
                   VALUES (%s,%s) ON CONFLICT DO NOTHING""",
                (tournament_id, email))

    def ranked_tournament(self, season_id=None, active=True):
        if season_id is None:
            season_id = self.conn.execute(
                "INSERT INTO public.temporadas DEFAULT VALUES RETURNING id"
            ).fetchone()[0]
        return self.conn.execute(
            """INSERT INTO public.torneios(
                status_torneio, ranking_ativo, temporada_id,
                pontos_campeao, pontos_vice
            ) VALUES (%s, true, %s, 10, 6) RETURNING id""",
            ('em_andamento' if active else 'cancelado', season_id)
        ).fetchone()[0], season_id

    def championship(self, tournament_id):
        return self.conn.execute(
            """SELECT status_torneio, campeao_email, vice_campeao_email,
                      ranking_processado, finalizado_em
                 FROM public.torneios WHERE id=%s""",
            (tournament_id,)).fetchone()

    def ranking(self, season):
        return self.conn.execute(
            """SELECT usuario_email,pontos,vitorias,podios
                 FROM public.ranking_temporada
                WHERE temporada_id=%s ORDER BY usuario_email""",
            (season,)).fetchall()

    def test_two_players_auto_champion_without_ranking(self):
        t = self.tournament()
        self.enroll(t, "a@test", "b@test")
        m = self.match(t, 1, "a@test", "b@test")
        self.finish(m, "a@test")
        state = self.championship(t)
        self.assertEqual(state[:4], ('finalizado', 'a@test', 'b@test', False))
        self.assertIsNotNone(state[4])
        self.assertEqual(self.round_matches(t, 2), [])

    def test_ranked_final_awards_once_even_after_repeated_updates(self):
        t, s = self.ranked_tournament()
        self.enroll(t, "a@test", "b@test")
        self.conn.execute(
            """INSERT INTO public.ranking_temporada
               (temporada_id, usuario_email, pontos, vitorias, podios)
               VALUES (%s,'a@test', 5, 2, 1)""", (s,))
        m = self.match(t, 1, "a@test", "b@test")
        self.finish(m, "a@test")
        self.assertEqual(self.championship(t)[:4],
                         ('finalizado', 'a@test', 'b@test', True))
        self.assertEqual(self.ranking(s),
                         [('a@test', 15, 3, 2), ('b@test', 6, 0, 1)])
        self.finish(m, "a@test")
        self.assertEqual(self.ranking(s),
                         [('a@test', 15, 3, 2), ('b@test', 6, 0, 1)])

    def test_four_player_tournament_advances_and_closes(self):
        t, s = self.ranked_tournament()
        self.enroll(t, "a@test", "b@test", "c@test", "d@test")
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.finish(a, "a@test")
        self.assertEqual(self.championship(t)[0], 'em_andamento')
        self.finish(b, "d@test")
        self.assertEqual(self.round_matches(t, 2),
                         [('a@test', 'd@test', 'pendente')])
        final = self.conn.execute(
            "SELECT id FROM public.partidas_torneio WHERE torneio_id=%s AND rodada=2",
            (t,)).fetchone()[0]
        self.finish(final, "d@test")
        self.assertEqual(self.championship(t)[:4],
                         ('finalizado', 'd@test', 'a@test', True))
        self.assertEqual(self.ranking(s),
                         [('a@test', 6, 0, 1), ('d@test', 10, 1, 1)])

    def test_unregistered_finalist_never_closes_tournament(self):
        t, s = self.ranked_tournament()
        self.enroll(t, "a@test")
        m = self.match(t, 1, "a@test", "b@test")
        self.finish(m, "a@test")
        self.assertEqual(self.championship(t)[0], 'em_andamento')
        self.assertEqual(self.ranking(s), [])

    def test_bye_cannot_create_champion(self):
        t = self.tournament()
        self.enroll(t, "a@test", "b@test")
        m = self.match(t, 1, "a@test", None)
        self.finish(m, "a@test")
        self.assertEqual(self.championship(t)[0], 'em_andamento')

    def test_cancelled_event_cannot_award_ranking(self):
        t, s = self.ranked_tournament(active=False)
        self.enroll(t, "a@test", "b@test")
        m = self.match(t, 1, "a@test", "b@test")
        self.finish(m, "a@test")
        self.assertEqual(self.championship(t)[0], 'cancelado')
        self.assertEqual(self.ranking(s), [])

    def test_final_does_not_close_with_incomplete_previous_round(self):
        t, s = self.ranked_tournament()
        self.enroll(t, "a@test", "b@test", "c@test", "d@test")
        self.match(t, 1, "a@test", "b@test")
        self.match(t, 2, "c@test", "d@test")
        final = self.match(t, 1, "a@test", "c@test", round_=2)
        self.finish(final, "a@test")
        self.assertEqual(self.championship(t)[0], 'em_andamento')
        self.assertEqual(self.ranking(s), [])

    def test_final_does_not_close_if_finalists_do_not_match_bracket(self):
        t, s = self.ranked_tournament()
        self.enroll(t, "a@test", "b@test", "c@test", "d@test")
        a = self.match(t, 1, "a@test", "b@test")
        b = self.match(t, 2, "c@test", "d@test")
        self.match(t, 1, "b@test", "c@test", round_=2)
        self.finish(a, "a@test")
        self.finish(b, "d@test")
        final_id = self.conn.execute(
            "SELECT id FROM public.partidas_torneio WHERE torneio_id=%s AND rodada=2",
            (t,)).fetchone()[0]
        self.finish(final_id, "b@test")
        self.assertEqual(self.championship(t)[0], 'em_andamento')
        self.assertEqual(self.ranking(s), [])

    def test_ranked_tournament_without_season_closes_without_points(self):
        t = self.conn.execute(
            """INSERT INTO public.torneios(status_torneio, ranking_ativo)
               VALUES ('em_andamento', true) RETURNING id""").fetchone()[0]
        self.enroll(t, "a@test", "b@test")
        m = self.match(t, 1, "a@test", "b@test")
        self.finish(m, "a@test")
        self.assertEqual(self.championship(t)[:4],
                         ('finalizado', 'a@test', 'b@test', False))

    def test_one_round_with_more_than_two_entries_is_not_a_final(self):
        t, s = self.ranked_tournament()
        self.enroll(t, "a@test", "b@test", "c@test")
        m = self.match(t, 1, "a@test", "b@test")
        self.finish(m, "a@test")
        self.assertEqual(self.championship(t)[0], 'em_andamento')
        self.assertEqual(self.ranking(s), [])



if __name__ == "__main__":
    unittest.main()
