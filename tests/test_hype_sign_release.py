"""Tests for the HYPE updater's offline release preparation.

No real production signing key is needed or generated by these tests.
"""
import base64
import importlib.util
import json
import os
import tempfile
import unittest
from pathlib import Path
from zipfile import ZipFile

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

SOURCE = Path(__file__).resolve().parents[1] / "tools" / "hype_sign_release.py"
spec = importlib.util.spec_from_file_location("hype_sign_release", SOURCE)
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)


def sample_fields():
    return {
        "release": "8",
        "version": "R7.19-ALPHA7-PREVIEW10.0.42",
        "url": "https://clan-hype.onrender.com/hype-updates/releases/hypeclient-r8.jar",
        "sha256": "a" * 64,
        "size": "9000000",
        "minecraft": "1.21.1",
        "mod_id": "hypeclient",
        "channel": "stable",
    }


class HypeReleaseTests(unittest.TestCase):
    def test_canonical_matches_client_field_order_and_final_newline(self):
        values = sample_fields()
        actual = release.canonical(values).decode("utf-8")
        self.assertEqual(actual, "".join(k + "=" + values[k] + "\n" for k in release.FIELDS))
        self.assertTrue(actual.endswith("channel=stable\n"))
        self.assertNotIn("signature=", actual)

    def test_rejects_untrusted_url_and_nonstable_channel(self):
        for key, bad_value in (
            ("url", "https://evil.example/hype-updates/releases/hypeclient-r8.jar"),
            ("url", "http://clan-hype.onrender.com/hype-updates/releases/hypeclient-r8.jar"),
            ("url", "https://clan-hype.onrender.com/hype-updates/releases/hypeclient-r9.jar"),
            ("channel", "preview"),
            ("mod_id", "hype_pokedex"),
            ("release", "0"),
        ):
            with self.subTest(key=key, bad_value=bad_value):
                values = sample_fields()
                values[key] = bad_value
                with self.assertRaises(release.ReleaseError):
                    release.canonical(values)

    def test_existing_unrelated_private_key_is_rejected(self):
        with tempfile.TemporaryDirectory() as folder:
            private = Ed25519PrivateKey.generate()
            key_path = Path(folder) / "unrelated.pem"
            key_path.write_bytes(private.private_bytes(
                serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption()))
            with self.assertRaisesRegex(release.ReleaseError, "DOES NOT MATCH"):
                release.load_matching_private_key(key_path)

    def test_inspect_identifies_fabric_hypeclient(self):
        with tempfile.TemporaryDirectory() as folder:
            jar = Path(folder) / "hypeclient.jar"
            with ZipFile(jar, "w") as archive:
                archive.writestr("fabric.mod.json", json.dumps({
                    "id": "hypeclient", "version": "R7.19-TEST"}))
                archive.writestr("data.bin", b"a" * 1500)
            report = release.inspect_jar(jar)
            self.assertEqual(report["mod_id"], "hypeclient")
            self.assertEqual(report["version"], "R7.19-TEST")
            self.assertEqual(len(report["sha256"]), 64)

    def test_rotated_key_is_read_from_explicitly_trusted_client(self):
        with tempfile.TemporaryDirectory() as folder:
            trusted = Path(folder) / "installed-rotated-client.jar"
            key = Ed25519PrivateKey.generate()
            spki = key.public_key().public_bytes(
                serialization.Encoding.DER,
                serialization.PublicFormat.SubjectPublicKeyInfo,
            )
            with ZipFile(trusted, "w") as archive:
                archive.writestr("fabric.mod.json", json.dumps({
                    "id": "hypeclient", "version": "R7.19-CHAVE-TESTE",
                }))
                archive.writestr(release.UPDATER_CLASS,
                                 b"\\xca\\xfe\\xba\\xbe" + b"test-bytecode" +
                                 base64.b64encode(spki) + os.urandom(2200))
            self.assertEqual(release.public_key_embedded_in_client(trusted), spki)
            private = Path(folder) / "local-private.pem"
            private.write_bytes(key.private_bytes(
                serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption(),
            ))
            self.assertIsInstance(release.load_matching_private_key(private, spki),
                                  Ed25519PrivateKey)
            with self.assertRaisesRegex(release.ReleaseError, "DOES NOT MATCH"):
                release.load_matching_private_key(private)

    def test_rejects_other_mod(self):
        with tempfile.TemporaryDirectory() as folder:
            jar = Path(folder) / "other.jar"
            with ZipFile(jar, "w") as archive:
                archive.writestr("fabric.mod.json", '{"id":"other","version":"1.0"}')
                archive.writestr("data.bin", b"a" * 1500)
            with self.assertRaisesRegex(release.ReleaseError, "Only the HYPE Client"):
                release.inspect_jar(jar)


if __name__ == "__main__":
    unittest.main()
